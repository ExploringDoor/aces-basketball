import assert from 'node:assert/strict';
import { windowEvents, diffEvents, describeChanges, teamsForGroup, changeEmail, hasChanges } from '../api/_feedwatch.js';
const now = Date.parse('2026-11-16T12:00:00-05:00');
const ev = (at, title, where = '', allDay = false) => ({ at, title, where, allDay });
const old = windowEvents([ev('2026-11-19T20:30:00.000Z', 'Aces Varsity Practice', 'Kobe Bryant Gym'), ev('2026-11-21T00:00:00.000Z', 'Varsity Game vs Radnor', 'Radnor HS'), ev('2026-11-25T20:30:00.000Z', 'Aces Varsity Practice', 'Kobe Bryant Gym'), ev('2026-12-20T20:30:00.000Z', 'Far away', '')], now);
assert.equal(old.length, 3, 'window keeps 14 days');
const next = windowEvents([ev('2026-11-19T21:15:00.000Z', 'Aces Varsity Practice', 'Kobe Bryant Gym'), ev('2026-11-21T00:00:00.000Z', 'Varsity Game vs Radnor', 'Downs Gym'), ev('2026-11-22T15:00:00.000Z', 'Film session', 'Room 204')], now);
const d = diffEvents(old, next);
assert.equal(d.moved.length, 1, 'time change is a move, not add+remove');
assert.equal(d.relocated.length, 1);
assert.equal(d.added.length, 1);
assert.equal(d.removed.length, 1, 'the 11/25 practice is gone');
assert.ok(hasChanges(d));
const lines = describeChanges(d);
assert.ok(lines.some((l) => /moved from 3:30 pm to 4:15 pm/.test(l)), lines.join(' | '));
assert.ok(lines.some((l) => /is now at Downs Gym instead of Radnor HS/.test(l)));
assert.ok(lines.some((l) => /^Added: Film session/.test(l)));
assert.ok(lines.some((l) => /^Cancelled: Aces Varsity Practice/.test(l)));
assert.ok(!hasChanges(diffEvents(next, next)), 'same feed, no changes');
assert.deepEqual(teamsForGroup('Varsity', ['Varsity', 'JV', '9th Grade']), ['Varsity']);
assert.deepEqual(teamsForGroup('9th', ['Varsity', 'JV', '9th Grade']), ['9th Grade']);
assert.deepEqual(teamsForGroup('', ['Varsity', 'JV', '9th Grade']), ['Varsity', 'JV', '9th Grade']);
const m = changeEmail({ group: 'Varsity', lines, siteUrl: 'https://x.test', teamName: 'Aces' });
assert.ok(/Varsity schedule: 4 changes/.test(m.subject), m.subject);
assert.ok(m.html.includes('Open the playbook') && m.text.includes('/playbook'));
console.log('feedwatch tests ok');
